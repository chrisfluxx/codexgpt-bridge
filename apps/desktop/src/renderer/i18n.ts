export const CATALOGS: Readonly<Record<DesktopSettings["locale"], Catalog>> = {
  en,
  "zh-TW": zhTW,
  "zh-CN": zhCN,
  ja,
  ko,
};

export type Translator = (
  key: MessageKey,
  values?: Readonly<Record<string, string | number>>,
) => string;

export function translator(locale: DesktopSettings["locale"]): Translator {
  const catalog = CATALOGS[locale] ?? CATALOGS.en;
  return (key, values = {}) =>
    Object.entries(values).reduce(
      (message, [name, value]) =>
        message.replaceAll(`{${name}}`, String(value)),
      catalog[key],
    );
}
