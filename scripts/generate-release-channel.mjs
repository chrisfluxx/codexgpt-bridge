import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import process from "node:process";
import { URL } from "node:url";

const requireUrl = process.argv.includes("--require-url");
const rawUrl = process.env.CODEXGPT_BRIDGE_UPDATE_MANIFEST_URL?.trim() ?? "";

let updateManifestUrl;
if (rawUrl) {
  const parsed = new URL(rawUrl);
  if (parsed.protocol !== "https:" || parsed.username || parsed.password) {
    throw new Error(
      "CODEXGPT_BRIDGE_UPDATE_MANIFEST_URL must be an HTTPS URL without credentials.",
    );
  }
  updateManifestUrl = parsed.href;
} else if (requireUrl) {
  throw new Error(
    "CODEXGPT_BRIDGE_UPDATE_MANIFEST_URL is required for a public release.",
  );
}

const target = resolve("apps/desktop/src/main/release-channel.generated.ts");
const source = `// Generated by scripts/generate-release-channel.mjs.\n// Production packaging overwrites this value from CODEXGPT_BRIDGE_UPDATE_MANIFEST_URL.\nexport const BUNDLED_UPDATE_MANIFEST_URL: string | undefined =${
  updateManifestUrl ? `\n  ${JSON.stringify(updateManifestUrl)}` : " undefined"
};\n`;

await writeFile(target, source, "utf8");
process.stdout.write(
  updateManifestUrl
    ? `Bundled update feed: ${updateManifestUrl}\n`
    : "Bundled update feed: disabled (development/local build)\n",
);
